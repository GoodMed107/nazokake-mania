def random_odai(count, exclude=None):
    """重複しないお題を count 個返す。exclude は既出お題の集合。"""
    exclude = exclude or set()
    pool = [t[0] for t in ODAI if t[0] not in exclude]
    random.shuffle(pool)
    if len(pool) < count:
        # 足りなければ全体から補充
        extra = [t[0] for t in ODAI]
        random.shuffle(extra)
        pool = list(dict.fromkeys(pool + extra))
    return pool[:count]
